export type TranslationKey = keyof (typeof translations)['en'];

interface LanguageContextType {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey | string, replacements?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem('yaqeen-locale');
    if (saved === 'uz' || saved === 'ru' || saved === 'en') return saved;

    const browserLang = navigator.language.slice(0, 2);
    if (browserLang === 'uz' || browserLang === 'ru') return browserLang as Locale;
    return 'en';
  });

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    localStorage.setItem('yaqeen-locale', newLocale);
  };

  const t = (key: string, replacements?: Record<string, string | number>): string => {
    const dict = translations[locale] || translations['en'];
    // @ts-ignore
    let text = dict[key] || translations['en'][key] || key;

    if (replacements) {
      Object.entries(replacements).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }
    return text;
  };

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t }}>{children}</LanguageContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useTranslation must be used within a LanguageProvider');
  }
  return context;
}
